import assert from 'node:assert/strict';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import mongoose from 'mongoose';
import { MongoMemoryServer } from 'mongodb-memory-server';
import jwt from 'jsonwebtoken';
import User from '../src/models/User.js';
import Job from '../src/models/Job.js';
import OutreachThread from '../src/models/OutreachThread.js';
import OutreachTask from '../src/models/OutreachTask.js';
import OutreachUsage from '../src/models/OutreachUsage.js';
import OutreachDiscoveryCache from '../src/models/OutreachDiscoveryCache.js';
import OutreachEmailCache from '../src/models/OutreachEmailCache.js';
import { requestDiscovery, processDiscoveryTask, saveContact, requestDraft, updateThread, listThreads, dispatchOutreachDrafts, dispatchOutreachDiscoveries } from '../src/services/outreachService.js';
import { drainDraftTasks } from '../outreach/runner.js';
import { reserveUsage } from '../src/services/outreachUsage.js';

test('Mongo outreach queue lifecycle: explicit discovery, deduplication, cache, draft CAS and deletion', { timeout: 90000 }, async t => {
  process.env.MONGOMS_RUNTIME_DOWNLOAD = 'false';
  const mongo = new MongoMemoryServer({ binary: { version: '8.2.6', downloadDir: fileURLToPath(new URL('../.cache/mongodb-binaries/', import.meta.url)) } });
  t.after(async () => { await mongoose.disconnect(); await mongo.stop(); });
  await mongo.start();
  await mongoose.connect(mongo.getUri(), { dbName: 'outreach_lifecycle_test' });
  await Promise.all([OutreachThread, OutreachTask, OutreachUsage, OutreachDiscoveryCache, OutreachEmailCache].map(model => model.init()));
  const owner = new mongoose.Types.ObjectId();
  const other = new mongoose.Types.ObjectId();
  const jobId = new mongoose.Types.ObjectId();
  await User.collection.insertMany([{ _id: owner, email: 'owner@example.test', profile: { name: 'Candidate', aboutYou: 'React developer', experienceProjects: 'Weather app' } }, { _id: other, email: 'other@example.test' }]);
  await Job.collection.insertOne({ _id: jobId, title: 'Frontend Engineer', company: 'Example Corp', companyDomain: 'example.com', location: 'Pune, India', isPublicIndia: true, status: 'active', description: 'Build React applications.', fingerprint: 'outreach-fixture' });
  assert.equal(await OutreachTask.countDocuments(), 0, 'reading jobs must never create discovery tasks');
  const oldKey = process.env.TAVILY_API_KEY;
  const oldProvider = process.env.OUTREACH_DISCOVERY_PROVIDER;
  process.env.OUTREACH_DISCOVERY_PROVIDER = 'tavily';
  t.after(() => { if (oldProvider === undefined) delete process.env.OUTREACH_DISCOVERY_PROVIDER; else process.env.OUTREACH_DISCOVERY_PROVIDER = oldProvider; });
  process.env.TAVILY_API_KEY = 'fixture-no-network';
  t.after(() => { if (oldKey === undefined) delete process.env.TAVILY_API_KEY; else process.env.TAVILY_API_KEY = oldKey; });
  const options = { schedule: () => {} };
  const requests = await Promise.all(Array.from({ length: 6 }, () => requestDiscovery(owner, { jobId: String(jobId) }, options)));
  assert.equal(new Set(requests.map(row => String(row._id))).size, 1);
  const task = requests[0];
  assert.equal(await OutreachUsage.countDocuments(), 1, 'duplicate requests reserve one userday allowance');
  let searchCalls = 0;
  const providers = { search: async () => { searchCalls++; return [{ title: 'Jane Doe - Engineering Manager at Example Corp | LinkedIn', url: 'https://www.linkedin.com/in/jane-doe', content: 'Jane Doe leads the engineering team at Example Corp.' }]; }, findEmail: async () => ({ email: 'jane@example.com', emailStatus: 'verified' }) };
  await Promise.all(Array.from({ length: 5 }, () => processDiscoveryTask(task._id, providers)));
  assert.equal(searchCalls, 1);
  const completed = await OutreachTask.findById(task._id).lean();
  assert.equal(completed.status, 'completed');
  assert.equal(completed.result.contacts[0].emailStatus, 'verified');
  assert.equal(await OutreachThread.countDocuments(), 0, 'discovery alone never saves contacts');
  const cached = await requestDiscovery(other, { jobId: String(jobId) }, options);
  assert.equal(cached.status, 'completed');
  assert.equal(String(cached.user), String(other));
  assert.equal(await OutreachUsage.countDocuments({ user: other }), 0);
  await assert.rejects(saveContact(other, { taskId: String(task._id), contactIndex: 0 }), /Contact not found/);
  const threads = await Promise.all(Array.from({ length: 4 }, () => saveContact(owner, { taskId: String(task._id), contactIndex: 0 })));
  assert.equal(await OutreachThread.countDocuments(), 1);
  const thread = threads[0];
  // Exercise the real middleware stack without ever calling a paid provider.
  process.env.NODE_ENV = 'test';
  process.env.JWT_SECRET = 'outreach-http-fixture-secret-only-123456789';
  process.env.CORS_ORIGIN = 'http://localhost:5173';
  const { createApp } = await import('../src/app.js');
  const server = createApp().listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const csrfResponse = await fetch(`${base}/api/auth/csrf-token`, { headers: { Origin: process.env.CORS_ORIGIN } });
  const { token: csrf } = await csrfResponse.json();
  const csrfCookie = csrfResponse.headers.getSetCookie().map(cookie => cookie.split(';')[0]).join('; ');
  async function http(path, { method = 'GET', body, as = owner, withCsrf = true } = {}) {
    const auth = as ? `jobverify_token=${jwt.sign({ id: String(as), sessionVersion: 0 }, process.env.JWT_SECRET)}` : '';
    const response = await fetch(`${base}/api/user/outreach${path}`, { method, headers: { 'Content-Type': 'application/json', Origin: process.env.CORS_ORIGIN, Cookie: `${auth}; ${csrfCookie}`, ...(withCsrf ? { 'X-CSRF-Token': csrf } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json() };
  }
  assert.equal((await http('/threads', { as: null })).status, 401);
  assert.equal((await http(`/tasks/${task._id}`, { as: other })).status, 404);
  assert.equal((await http('/discoveries', { method: 'POST', body: { jobId: String(jobId) }, withCsrf: false })).status, 403);
  assert.equal((await http('/discoveries', { method: 'POST', body: { jobId: { $ne: null } } })).status, 400);
  assert.equal((await http(`/threads/${thread._id}`, { method: 'PATCH', body: { status: 'interview' }, as: other })).status, 404);
  const cacheHttp = await http('/discoveries', { method: 'POST', body: { jobId: String(jobId) } });
  assert.equal(cacheHttp.status, 200);
  assert.equal(cacheHttp.body.data.status, 'completed');
  assert.equal(cacheHttp.body.data.input, undefined);
  assert.equal((await http('/threads')).body.data.length, 1);
  assert.equal(searchCalls, 1, 'GET requests and cache hits never call discovery');
  const user = await User.findById(owner).lean();
  let dispatches = 0;
  const draftTasks = await Promise.all(Array.from({ length: 4 }, () => requestDraft(user, String(thread._id), { dispatch: async () => { dispatches++; } })));
  assert.equal(dispatches, 1);
  assert.equal(new Set(draftTasks.map(row => String(row._id))).size, 1);
  assert.equal((await listThreads(owner))[0].draftTask.status, 'queued');
  await updateThread(owner, String(thread._id), { draft: { emailBody: 'My intentional edit' }, revision: 0 });
  const generated = { linkedin: 'Hello Jane', emailSubject: 'Frontend Engineer', emailBody: 'I built a weather app.' };
  const stale = await drainDraftTasks({ generate: async () => generated });
  assert.equal(stale.failed, 1);
  assert.equal((await OutreachThread.findById(thread._id)).draft.emailBody, 'My intentional edit');
  await requestDraft(user, String(thread._id), { dispatch: async () => {} });
  const success = await drainDraftTasks({ generate: async () => generated });
  assert.equal(success.completed, 1);
  assert.equal((await OutreachThread.findById(thread._id)).draft.emailBody, generated.emailBody);
  await requestDraft(user, String(thread._id), { dispatch: async () => {} });
  const deleted = await drainDraftTasks({ generate: async () => { await User.deleteOne({ _id: owner }); await OutreachThread.deleteMany({ user: owner }); return generated; } });
  assert.equal(deleted.completed, 0);
  assert.equal(await OutreachThread.countDocuments({ user: owner }), 0);
  assert.equal(await OutreachTask.countDocuments({ user: owner, status: 'running' }), 0);

  // A changed stored job cannot reuse the stale discovery hash; Hunter failures retain contact evidence.
  await Job.updateOne({ _id: jobId }, { $set: { description: 'Updated job requirements.' } });
  const changed = await requestDiscovery(other, { jobId: String(jobId) }, options);
  assert.equal(changed.status, 'queued');
  const withoutEmail = await processDiscoveryTask(changed._id, { ...providers, search: async context => { searchCalls++; return [{ title: 'Alex Brown - Engineering Manager at Example Corp | LinkedIn', url: 'https://www.linkedin.com/in/alex-brown', content: `Alex Brown is an engineering manager at ${context.company}.` }]; }, findEmail: async () => { throw new Error('Fixture provider outage'); } });
  assert.equal(withoutEmail.contacts[0].name, 'Alex Brown');
  assert.equal(withoutEmail.contacts[0].emailStatus, 'unavailable');
  assert.equal(searchCalls, 2);
  await Job.updateOne({ _id: jobId }, { $set: { status: 'inactive' } });
  await assert.rejects(requestDiscovery(other, { jobId: String(jobId) }, options), error => error.statusCode === 404);

  // A shared cap cannot be overshot by concurrent reservations.
  const reservations = await Promise.allSettled(Array.from({ length: 12 }, () => reserveUsage('fixture:concurrency', 5)));
  assert.equal(reservations.filter(row => row.status === 'fulfilled').length, 5);
  assert.equal((await OutreachUsage.findOne({ key: 'fixture:concurrency' })).used, 5);

  const actionNames = ['OUTREACH_ACTIONS_ENABLED', 'OUTREACH_ACTIONS_FREE_CONFIRMED', 'GITHUB_REPO', 'OUTREACH_ACTIONS_MONTHLY_RUN_LIMIT', 'GITHUB_PAT'];
  const previousActions = actionNames.map(name => process.env[name]);
  Object.assign(process.env, { OUTREACH_ACTIONS_ENABLED: 'true', OUTREACH_ACTIONS_FREE_CONFIRMED: 'true', GITHUB_REPO: 'fixture/repository', OUTREACH_ACTIONS_MONTHLY_RUN_LIMIT: '2', GITHUB_PAT: 'fixture-no-network' });
  t.after(() => { for (const [index, name] of actionNames.entries()) { if (previousActions[index] === undefined) delete process.env[name]; else process.env[name] = previousActions[index]; } });
  let dispatched = 0;
  const github = async (_repo, endpoint, options) => { if (endpoint.includes('/runs?')) return { workflow_runs: [] }; if (!endpoint) return { default_branch: 'main' }; assert.equal(options.body.ref, 'main'); dispatched++; return null; };
  const workflowNow = new Date('2026-10-21T13:00:00.000Z');
  await OutreachUsage.create({ key: 'actions:2026-10', used: 120, expiresAt: new Date('2026-12-25T13:00:00.000Z') });
  await dispatchOutreachDrafts({ request: github, now: workflowNow });
  await dispatchOutreachDiscoveries({ request: github, now: workflowNow });
  await dispatchOutreachDrafts({ request: github, now: workflowNow });
  assert.equal(dispatched, 3, 'past usage and old monthly settings cannot block discovery or drafting');
  assert.equal((await OutreachUsage.findOne({ key: 'actions:2026-10' })).used, 123, 'usage stays observable without resetting or limiting its counter');
  const nextMonth = new Date('2026-11-01T13:00:00.000Z');
  await Promise.all([dispatchOutreachDrafts({ request: github, now: nextMonth }), dispatchOutreachDiscoveries({ request: github, now: nextMonth })]);
  assert.equal(dispatched, 5);
  assert.equal((await OutreachUsage.findOne({ key: 'actions:2026-11' })).used, 2, 'concurrent workflows initialize and increment one telemetry counter');
  process.env.OUTREACH_ACTIONS_FREE_CONFIRMED = 'false';
  await assert.rejects(dispatchOutreachDrafts({ request: async () => assert.fail('disabled Actions must make no requests') }), error => error.statusCode === 503);
});
