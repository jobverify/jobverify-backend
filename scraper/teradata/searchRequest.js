const canonical = value => JSON.stringify(value, (_, item) => item && typeof item === 'object' && !Array.isArray(item) ? Object.fromEntries(Object.keys(item).sort().map(k => [k, item[k]])) : item)
const expected = canonical(buildSearchJobsRequestBody())
export const isTeradataSearchRequest = body => {
  if (!body || typeof body !== 'object' || Array.isArray(body)) return false
  const variables = body.variables
  if (!variables || variables.first !== 100 || !Number.isSafeInteger(variables.start) || variables.start < 0 || variables.start > 900 || variables.start % 100) return false
  return canonical({...body, variables: {...variables, start: 0}}) === expected
}
