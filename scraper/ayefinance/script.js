import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import { attachInventoryEvidence, readInventoryEvidence } from '../../scraper-support/utils/inventoryEvidence.js'
import { collectNative, EMPLOYER_URL } from './native.js'

const currentDir = path.dirname(fileURLToPath(import.meta.url))

export const SOURCE = 'ayefinance'
export const COMPANY = 'Aye Finance'
export const FIRST_PARTY_ROOT_URL = 'https://www.ayefin.com/'

export const createAyeFinanceScraper = ({ fetchImpl = fetch, timeoutMs = 45000, now = () => new Date().toISOString() } = {}) => ({
  async run({ signal } = {}) {
    signal?.throwIfAborted()
    if (!Number.isSafeInteger(timeoutMs) || timeoutMs < 1 || timeoutMs > 180000) throw Error('Invalid Aye deadline')
    const controller = new AbortController(), retainedResponses = []
    const combined = signal ? AbortSignal.any([signal, controller.signal]) : controller.signal
    let timer, onAbort
    const evidence = reason => ({ status: 'discovery-only', surface: EMPLOYER_URL, firstParty: false,
      listingComplete: false, pagesFetched: retainedResponses.length, reportedTotal: null,
      indiaFacetCount: null, verifiedAt: now(), reason })
    const gap = (reason, cause) => Object.assign(new Error(`Aye Finance coverage gap: ${reason}`, { cause }), {
      code: 'AYEFINANCE_COVERAGE_GAP', partial: true, abortRetries: true, source: SOURCE,
      sourceListingComplete: false, lifecycleCleanupAllowed: false, retainedResponses,
      inventoryEvidence: evidence(reason),
    })
    const interrupted = new Promise((_, reject) => {
      onAbort = () => reject(combined.reason)
      combined.addEventListener('abort', onAbort, { once: true })
      timer = setTimeout(() => controller.abort(gap('aggregate fetch/body deadline exceeded')), timeoutMs)
    })
    const read = async (url, allowBlocked = false) => {
      combined.throwIfAborted()
      const response = await fetchImpl(url, { signal: combined, redirect: 'manual', headers: { Accept: 'text/html', 'User-Agent': 'Mozilla/5.0' } })
      combined.throwIfAborted()
      if (response.url !== url) throw gap('native final URL changed')
      if (response.status !== 200 && !(allowBlocked && response.status === 403)) throw Object.assign(gap(`native HTTP ${response.status}`), { status: response.status })
      let body
      if (response.body?.getReader) {
        const reader = response.body.getReader(), chunks = []
        let bytes = 0
        const cancel = () => { void Promise.resolve(reader.cancel(combined.reason)).catch(() => {}) }
        combined.addEventListener('abort', cancel, { once: true })
        try {
          while (true) {
            combined.throwIfAborted()
            const part = await reader.read()
            combined.throwIfAborted()
            if (part.done) break
            bytes += part.value.byteLength
            if (bytes > 5000000) { cancel(); throw gap('streamed native body exceeds byte bound') }
            chunks.push(Buffer.from(part.value))
          }
          body = Buffer.concat(chunks).toString('utf8')
        } finally { combined.removeEventListener('abort', cancel); reader.releaseLock?.() }
      } else body = await response.text()
      combined.throwIfAborted()
      if (typeof body !== 'string' || !body.trim() || Buffer.byteLength(body) > 5000000) throw gap('native body unavailable or oversized')
      retainedResponses.push({ url, finalUrl: response.url, status: response.status, body, capturedAt: now(), bodySHA256: createHash('sha256').update(body).digest('hex') })
      if (response.status === 403 && !/Generated by cloudfront.*CloudFront/s.test(body)) throw gap('unreviewed corporate access block')
      return body
    }
    try {
      return await Promise.race([interrupted, (async () => {
        await read(FIRST_PARTY_ROOT_URL, true)
        const { jobs, reason, observations } = await collectNative({ read, now })
        const result = attachInventoryEvidence(jobs, evidence(reason))
        Object.defineProperty(result, 'nativeCollectionEvidence', { value: { observations, retainedResponses, lifecycleCleanupAllowed: false } })
        return result
      })()])
    } catch (error) {
      if (signal?.aborted) throw signal.reason
      if (error?.code === 'AYEFINANCE_COVERAGE_GAP') throw error
      throw gap('native discovery failed; company inventory unknown', error)
    } finally {
      clearTimeout(timer)
      combined.removeEventListener('abort', onAbort)
      controller.abort(gap('inspection ended'))
    }
  },
})

export const run = async (options = {}) => createAyeFinanceScraper(options).run(options)

const isDirectExecution = process.argv[1]
  ?.replaceAll('\\', '/')
  .endsWith('/scraper/ayefinance/script.js')

if (isDirectExecution) {
  const jobs = await run()
  if (readInventoryEvidence(jobs)?.listingComplete !== true) {
    if (process.argv.includes('--dry-run')) {
      const { writeFile } = await import('node:fs/promises')
      await writeFile(path.join(currentDir, 'inventory-evidence.json'), JSON.stringify(readInventoryEvidence(jobs), null, 2))
    }
    console.error(readInventoryEvidence(jobs)?.reason)
    process.exitCode = 1
  }
}
