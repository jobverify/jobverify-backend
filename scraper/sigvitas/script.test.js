test('Sigvitas sentinel pins the verified first-party no-public-jobs surface', async () => {
  const sigvitas = await loadModule()
  assert.ok(sigvitas, 'Expected scraper module at ./script.js')

  assert.equal(sigvitas.SOURCE, 'sigvitas')
  assert.equal(sigvitas.COMPANY, 'Sigvitas')
  assert.equal(sigvitas.HOMEPAGE_URL, 'https://sigvitas.com/')
  assert.equal(sigvitas.CONTACT_URL, 'https://sigvitas.com/get-in-touch/')
  assert.equal(sigvitas.SITEMAP_INDEX_URL, 'https://sigvitas.com/sitemap.xml')
  assert.equal(sigvitas.PAGE_SITEMAP_URL, 'https://sigvitas.com/page-sitemap.xml')
  assert.equal(
    sigvitas.PAGES_API_URL,
    'https://sigvitas.com/wp-json/wp/v2/pages?per_page=100&_fields=slug,link,title,status',
  )
  assert.deepEqual(sigvitas.NO_PUBLIC_CAREERS_ROUTE_URLS, [
    'https://sigvitas.com/careers/',
    'https://sigvitas.com/careers',
    'https://sigvitas.com/career/',
    'https://sigvitas.com/career',
    'https://sigvitas.com/jobs/',
    'https://sigvitas.com/jobs',
    'https://sigvitas.com/join-us/',
    'https://sigvitas.com/join-us',
  ])
  assert.equal(sigvitas.hasOfficialHomepageSignal(homepageHtml), true)
  assert.equal(sigvitas.hasOfficialContactSignal(contactHtml), true)
  assert.equal(sigvitas.hasOfficialSitemapIndexSignal(sitemapIndexXml), true)
  assert.equal(sigvitas.hasOfficialPageSitemapSignal(pageSitemapXml), true)
  assert.equal(sigvitas.hasOfficialPagesApiSignal(pagesApiJson), true)
  assert.equal(sigvitas.hasPublicJobsSignal(homepageHtml), false)
  assert.equal(sigvitas.hasPublicJobsSignal(contactHtml), false)
  assert.equal(sigvitas.hasFirstPartyCareerLikeLink(homepageHtml), false)
  assert.equal(sigvitas.hasFirstPartyCareerLikeLink(contactHtml), false)
  assert.equal(sigvitas.isVerifiedMissingCareerRoute(missingCareerRoutePage), true)
})

test('Sigvitas sentinel returns no jobs only while the verified first-party surfaces stay unchanged', async () => {
  const sigvitas = await loadModule()
  assert.ok(sigvitas, 'Expected scraper module at ./script.js')

  const requestedUrls = []
  const jobs = await sigvitas.createSigvitasScraper().run({
    fetchPage: async (url) => {
      requestedUrls.push(url)

      if (url === sigvitas.HOMEPAGE_URL) return { status: 200, url, html: homepageHtml }
      if (url === sigvitas.CONTACT_URL) return { status: 200, url, html: contactHtml }
      if (url === sigvitas.SITEMAP_INDEX_URL) return { status: 200, url, html: sitemapIndexXml }
      if (url === sigvitas.PAGE_SITEMAP_URL) return { status: 200, url, html: pageSitemapXml }
      if (url === sigvitas.PAGES_API_URL) return { status: 200, url, html: pagesApiJson }
      if (sigvitas.NO_PUBLIC_CAREERS_ROUTE_URLS.includes(url)) return { ...missingCareerRoutePage, url }

      throw new Error(`Unexpected Sigvitas URL: ${url}`)
    },
  })

  assert.deepEqual(requestedUrls, [
    sigvitas.HOMEPAGE_URL,
    sigvitas.CONTACT_URL,
    sigvitas.SITEMAP_INDEX_URL,
    sigvitas.PAGE_SITEMAP_URL,
    sigvitas.PAGES_API_URL,
    ...sigvitas.NO_PUBLIC_CAREERS_ROUTE_URLS,
  ])
  assert.deepEqual(jobs, [])
})

