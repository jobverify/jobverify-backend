test('Sigvitas sentinel fails closed when the verified no-public-careers contract drifts', async () => {
  const sigvitas = await loadModule()
  assert.ok(sigvitas, 'Expected scraper module at ./script.js')

  await assert.rejects(
    sigvitas.createSigvitasScraper().run({
      fetchPage: async (url) => {
        if (url === sigvitas.HOMEPAGE_URL) {
          return {
            status: 200,
            url,
            html: '<html><body><h1>Unexpected homepage</h1></body></html>',
          }
        }

        throw new Error(`Unexpected Sigvitas URL: ${url}`)
      },
    }),
    /homepage/i,
  )

  await assert.rejects(
    sigvitas.createSigvitasScraper().run({
      fetchPage: async (url) => {
        if (url === sigvitas.HOMEPAGE_URL) return { status: 200, url, html: homepageHtml }
        if (url === sigvitas.CONTACT_URL) return { status: 200, url, html: contactHtml }
        if (url === sigvitas.SITEMAP_INDEX_URL) return { status: 200, url, html: sitemapIndexXml }
        if (url === sigvitas.PAGE_SITEMAP_URL) return { status: 200, url, html: pageSitemapXml }
        if (url === sigvitas.PAGES_API_URL) {
          return {
            status: 200,
            url,
            html: JSON.stringify([
              { slug: 'home', status: 'publish', link: sigvitas.HOMEPAGE_URL, title: { rendered: 'Home' } },
              {
                slug: 'careers',
                status: 'publish',
                link: 'https://sigvitas.com/careers/',
                title: { rendered: 'Careers' },
              },
            ]),
          }
        }

        throw new Error(`Unexpected Sigvitas URL: ${url}`)
      },
    }),
    /pages api/i,
  )

  await assert.rejects(
    sigvitas.createSigvitasScraper().run({
      fetchPage: async (url) => {
        if (url === sigvitas.HOMEPAGE_URL) return { status: 200, url, html: homepageHtml }
        if (url === sigvitas.CONTACT_URL) return { status: 200, url, html: contactHtml }
        if (url === sigvitas.SITEMAP_INDEX_URL) return { status: 200, url, html: sitemapIndexXml }
        if (url === sigvitas.PAGE_SITEMAP_URL) return { status: 200, url, html: pageSitemapXml }
        if (url === sigvitas.PAGES_API_URL) return { status: 200, url, html: pagesApiJson }
        if (url === sigvitas.NO_PUBLIC_CAREERS_ROUTE_URLS[0]) {
          return {
            status: 200,
            url,
            html: '<html><body><h1>Current Openings</h1><a href="/careers/software-engineer">Apply now</a></body></html>',
          }
        }
        if (sigvitas.NO_PUBLIC_CAREERS_ROUTE_URLS.slice(1).includes(url)) return { ...missingCareerRoutePage, url }

        throw new Error(`Unexpected Sigvitas URL: ${url}`)
      },
    }),
    /no-public-careers route changed/i,
  )
})
