      /(?:^|\/)(?:apply-now|career|careers|current[_-]?openings?|job[_-]?openings?|jobs|join-us(?:-\d+)?|openings|vacanc(?:y|ies)|work-with-us)(?:\.html?)?$/i.test(pathname)
